"""Discover artwork, create app copies, and generate a matching local DEV catalog."""

import argparse
import json
import re
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image

THEMES = {"coin": "동전", "dino": "공룡", "doll": "인형", "gem": "보석", "plant": "식물", "robot": "로봇"}


def discover_items(source):
    items = []
    missing = []
    for theme in THEMES:
        theme_dir = source / theme
        if not theme_dir.is_dir():
            continue
        for folder in theme_dir.iterdir():
            match = re.fullmatch(rf"{theme}_([0-9]{{2,}})", folder.name)
            if not folder.is_dir() or not match:
                continue
            number = int(match[1])
            code = f"{theme}_{number:02}"
            if number < 1 or folder.name != code:
                raise ValueError(f"Use canonical positive item numbers: {folder}")
            files = [folder / "complete" / f"{code}.png"] + [
                folder / "growth" / f"growth_{code}_{stage:02}.png"
                for stage in range(1, 6)
            ]
            missing.extend(str(path) for path in files if not path.is_file())
            items.append({"theme": theme, "code": code, "number": number, "files": files})
    if missing:
        raise ValueError("Missing artwork:\n" + "\n".join(missing))
    if not items:
        raise ValueError(f"No collection artwork found in {source}")
    return sorted(items, key=lambda item: (item["theme"], item["number"]))


def manifest_text(items):
    lines = [
        "// Generated by scripts/prepare-collection-assets.py. Static requires are required by Metro.",
        "export const collectionAssets: Record<string, { complete: number; growth: number[] }> = {",
    ]
    for item in items:
        code = item["code"]
        prefix = f"../../../../assets/collection/{item['theme']}/{code}"
        lines.extend([
            f"  {code.upper()}: {{",
            f"    complete: require('{prefix}/complete/{code}.webp'),",
            "    growth: [",
        ])
        for stage in range(1, 6):
            lines.append(f"      require('{prefix}/growth/growth_{code}_{stage:02}.webp'),")
        lines.extend(["    ],", "  },"])
    lines.append("};")
    return "\n".join(lines) + "\n"


def seed_text(items):
    rows = []
    for item in items:
        theme = item["theme"].upper()
        code = item["code"].upper()
        number = item["number"]
        name = f"테스트 {THEMES[item['theme']]} {number}"
        rows.append(f"  ('{theme}', 'DEV_{code}', '{name}', 24, {number}, true)")
    return (
        "-- Generated by scripts/prepare-collection-assets.py from available artwork.\n"
        "-- Local development/test catalog only. Production content belongs in a data migration.\n"
        "insert into public.collectible_catalog (theme_code, code, name, growth_goal, sort_order, is_active)\n"
        "values\n" + ",\n".join(rows) + "\non conflict (code) do nothing;\n"
    )


def prepare_collection(source, root):
    # Validate the entire source before overwriting any app file or catalog.
    items = discover_items(source)
    inputs = [path for item in items for path in item["files"]]
    destination = root / "assets/collection"

    def prepare(path):
        target = destination / path.relative_to(source).with_suffix(".webp")
        target.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(path) as image:
            image = image.convert("RGBA")
            image.thumbnail((640, 640), Image.Resampling.LANCZOS)
            image.save(target, "WEBP", quality=88, method=4)
        return path.stat().st_size, target.stat().st_size

    with ThreadPoolExecutor(max_workers=6) as pool:
        sizes = list(pool.map(prepare, inputs))
    manifest = root / "src/features/learning/assets/collection-assets.ts"
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(manifest_text(items), encoding="utf-8")
    seed = root / "supabase/seed.sql"
    seed.parent.mkdir(parents=True, exist_ok=True)
    seed.write_text(seed_text(items), encoding="utf-8")
    return {
        "items": len(items),
        "per_theme": {theme: sum(item["theme"] == theme for item in items) for theme in THEMES},
        "files": len(inputs),
        "source_bytes": sum(size[0] for size in sizes),
        "app_bytes": sum(size[1] for size in sizes),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Source assets/collection directory")
    parser.add_argument("--output-root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    try:
        print(json.dumps(prepare_collection(args.source, args.output_root)))
    except ValueError as error:
        raise SystemExit(str(error)) from error
